import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeUtil from "node:util";

import type { Link, MetaserverDb } from "./db.ts";

/**
 * Phones reach every t3 server through the metaserver: Caddy listens on one HTTPS
 * port per linked server and proxies it to that server's t3 URL. A port, not a
 * path, because T3 clients drop URL paths and DPoP signs the exact URL.
 */

export interface RelayConfig {
  /** The metaserver's tailnet DNS name. */
  publicHost: string;
  portBase: number;
  caddyFile: string;
  reloadCommand: string;
}

/** Null when T3_METASERVER_PUBLIC_HOST is unset: phones then connect to each t3 URL directly. */
export function relayConfigFromEnv(env: NodeJS.ProcessEnv = process.env): RelayConfig | null {
  const publicHost = env.T3_METASERVER_PUBLIC_HOST?.trim();
  if (!publicHost) return null;
  const portBase = Number(env.T3_METASERVER_RELAY_PORT_BASE ?? 9001);
  if (!Number.isInteger(portBase) || portBase < 1 || portBase > 65_535) {
    throw new Error("T3_METASERVER_RELAY_PORT_BASE must be a port number.");
  }
  return {
    publicHost,
    portBase,
    caddyFile: env.T3_METASERVER_CADDY_RELAYS ?? "/etc/caddy/t3-relays.caddy",
    reloadCommand: env.T3_METASERVER_CADDY_RELOAD ?? "systemctl reload caddy",
  };
}

export const relayUrl = (publicHost: string, port: number) => `https://${publicHost}:${port}`;

export function renderRelayCaddy(publicHost: string, links: ReadonlyArray<Link>): string {
  const blocks = links
    .filter((link) => link.relayPort !== null)
    .toSorted((a, b) => a.relayPort! - b.relayPort! || a.serverId.localeCompare(b.serverId))
    .map(
      (link) =>
        `# ${link.serverId}\n${publicHost}:${link.relayPort} {\n\treverse_proxy ${link.t3Url}\n}\n`,
    );
  return [
    "# Generated by t3-metaserver; edits are overwritten. One site per linked t3 server.\n",
    ...blocks,
  ].join("\n");
}

const execFile = NodeUtil.promisify(NodeChildProcess.execFile);

/**
 * Gives new links a relay port, rewrites the Caddy file when it changed and reloads
 * Caddy. Failures are logged and returned, never thrown: the relay is not worth
 * taking the metaserver or a CLI command down for.
 */
export async function syncRelay(
  db: MetaserverDb,
  config: RelayConfig,
  log: (message: string) => void = console.error,
): Promise<{ changed: boolean; error: string | null }> {
  let changed = false;
  try {
    db.assignRelayPorts(config.portBase);
    const content = renderRelayCaddy(config.publicHost, db.listLinks());
    const current = NodeFS.existsSync(config.caddyFile)
      ? NodeFS.readFileSync(config.caddyFile, "utf8")
      : null;
    if (current === content) {
      if ((NodeFS.statSync(config.caddyFile).mode & 0o777) !== 0o644)
        NodeFS.chmodSync(config.caddyFile, 0o644);
      return { changed, error: null };
    }
    const temporary = NodePath.join(
      NodePath.dirname(config.caddyFile),
      `.${NodePath.basename(config.caddyFile)}.tmp`,
    );
    NodeFS.writeFileSync(temporary, content);
    // Caddy runs as its own user, and the metaserver's unit sets UMask=0077.
    NodeFS.chmodSync(temporary, 0o644);
    NodeFS.renameSync(temporary, config.caddyFile);
    changed = true;
    const [command, ...args] = config.reloadCommand.split(" ").filter(Boolean);
    if (command) await execFile(command, args, { timeout: 60_000 });
    return { changed, error: null };
  } catch (cause) {
    const error = cause instanceof Error ? cause.message : String(cause);
    log(`t3-metaserver: relay sync failed: ${error}`);
    return { changed, error };
  }
}
